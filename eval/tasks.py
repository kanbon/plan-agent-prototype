"""Task definitions for the plan-reading eval: prompts, output schemas, ground truth.

Two tasks, matching the two experiments of the prototype:

  dimcheck  synthetic 1:100 floor plan (testplan.pdf) with planted dimension errors.
            The agent must find them by measuring the drawn geometry.
  takeoff   real 44-sheet bid set (realplan.pdf). The agent answers a tender
            question: how many ceiling air vents, which kinds, how big.

Ground truth was verified against the PDFs with PyMuPDF (see README, section
"Ground truth"). Numbers here are the reference the scorers compare against.
"""
from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
PYTHON = sys.executable   # the harness venv; has PyMuPDF and Pillow


@dataclass(frozen=True)
class Task:
    id: str
    pdf: str                       # file name in repo root
    question: str                  # the human question, verbatim
    framing: str                   # tool-neutral task framing (used in both conditions)
    schema: dict[str, Any]         # JSON schema for the structured final answer
    ground_truth: dict[str, Any]
    naive_pages: list[int] | None = None   # page indices to render for the naive condition (None = all)
    notes: str = ""

    @property
    def pdf_path(self) -> Path:
        path = ROOT / self.pdf
        if not path.exists():
            raise FileNotFoundError(
                f"{self.pdf} not found in the repo root. realplan.pdf is not committed; "
                "download it from https://www.maconbibb.us/wp-content/uploads/2016/06/Attachment-C-Drawings.pdf "
                "(see README Setup). testplan.pdf is generated by make_testplan.py."
            )
        return path

    @property
    def instructions(self) -> str:
        """Prompt for the tools condition: framing + file/tool facts."""
        return (f"{self.framing}\n\nThe plan is `{self.pdf}` in the working directory.\n\n"
                + TOOLS_HELP.format(python=PYTHON))


# ---------------------------------------------------------------------------
# Shared tool description (tools condition). Kept factual and short; the agent
# already knows how to drive a CLI. Paths are relative to the run workdir.
# ---------------------------------------------------------------------------
TOOLS_HELP = """\
Working directory contains the plan PDF and `plan_tools.py`, a viewport toolkit
(PyMuPDF based). Run it with `{python} plan_tools.py <cmd> ...`; use that same
interpreter for any ad-hoc Python (it has PyMuPDF and Pillow; do not pip install
anything). Commands:

  overview <pdf> [page]                       full page at 150 dpi -> overview.png
  zoom <pdf> <page> <x0> <y0> <x1> <y1> [dpi] region in PDF points -> zoom.png (default 300 dpi)
  text <pdf> <page>                           every word with its bounding box (x0,y0,x1,y1) in points
  snap <pdf> <page> <x> <y> [radius]          nearest vector edges to a point (exact coordinates)
  measure <pdf> <scale_denom> <x1> <y1> <x2> <y2>   distance between two points, converted with the scale
  layers <pdf>                                list CAD layers (OCGs); `layers <pdf> <page> <out.png> on=.. off=..` renders with a layer set
  mark <pdf> <page> <out.png> <spec.json>     draw labelled rects/lines/circles/text onto the page -> png

Every rendered image prints its page-space bbox so pixel positions convert to
page coordinates: page_x = bbox.x0 + px / img_w * (bbox.x1 - bbox.x0). Look at
rendered PNGs with the Read tool. You may also write ad-hoc Python against
PyMuPDF (`import fitz`) when that is the direct way to get an answer, e.g. to
tally text objects or sum vector lengths.
"""

